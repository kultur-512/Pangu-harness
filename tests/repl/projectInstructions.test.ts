// tests/repl/projectInstructions.test.ts
// /init closed loop (learn P0-2): readProjectVerificationBlock must extract
// the "## Verification commands" checklist from .panshalach/AGENTS.md so the
// PromptBuilder can inject concrete verification commands.

import { describe, it, beforeEach, afterEach } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { readProjectVerificationBlock, agentsPath } from '../../src/cli/repl/projectInstructions.js';

let ws: string;

describe('projectInstructions (P0-2 /init closed loop)', () => {
  beforeEach(() => { ws = fs.mkdtempSync(path.join(os.tmpdir(), 'pangu-pi-')); });
  afterEach(() => { fs.rmSync(ws, { recursive: true, force: true }); });

  it('returns null when AGENTS.md is absent', () => {
    assert.equal(readProjectVerificationBlock(ws), null);
  });

  it('extracts the verification checklist from an /init-generated AGENTS.md', () => {
    const md = [
      '# Project Instructions (generated by /init)',
      '',
      'Workspace: ' + ws,
      '',
      '## Tech stack',
      'typescript@^5.6.0',
      '',
      '## First-run commands',
      '- build: `build → tsc`',
      '- test:  `test → node --test`',
      '',
      '## Verification commands',
      'Run these before claiming success (harness Feedback discipline):',
      '- [ ] `test → node --test` passes',
      '- [ ] `build → tsc` passes',
      '- [ ] `tsc --noEmit` clean',
      '',
      '## Invariants',
      '- 测试必须通过',
      '',
    ].join('\n');
    fs.mkdirSync(path.join(ws, '.panshalach'), { recursive: true });
    fs.writeFileSync(agentsPath(ws), md, 'utf-8');

    const block = readProjectVerificationBlock(ws);
    assert.ok(block, 'block must be extracted');
    assert.ok(block.includes('node --test'), 'test command must appear');
    assert.ok(block.includes('tsc --noEmit'), 'tsc command must appear');
    assert.ok(block.includes('勾选'), 'checklist hint must appear (saw [ ] items)');
    assert.ok(!block.includes('## Invariants'), 'invariants section must NOT leak in');
    assert.ok(!block.includes('## Tech stack'), 'tech stack must NOT leak in');
  });

  it('caps the block size', () => {
    const lines = ['## Verification commands', 'Run these:'];
    for (let i = 0; i < 200; i++) lines.push(`- [ ] \`command number ${i} with a fairly long body to exceed caps\` passes`);
    fs.mkdirSync(path.join(ws, '.panshalach'), { recursive: true });
    fs.writeFileSync(agentsPath(ws), lines.join('\n'), 'utf-8');

    const block = readProjectVerificationBlock(ws)!;
    assert.ok(block.length <= 1300, `block too large: ${block.length}`);
    assert.ok(block.includes('截断') || !block.includes('command number 199'),
      'oversized block must be truncated');
  });
});
