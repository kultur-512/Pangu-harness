// src/cli/repl/commands/InitCommand.ts
// P1-T13 (L06): /init — generate a project instruction directory page
// (.zorge/AGENTS.md) with verification commands + invariants, plus an empty
// feature_list.json template. Idempotent (asks before overwriting existing).
// The buildAgentsMd + probeWorkspace logic is EXPORTED so the rich interactive
// path (/init in sseInteractive) reuses the exact same output (B-dual: the
// old inline simplified copy is gone).

import type { Command, CommandContext, CommandResult } from '../types.js';
import { writeFileSync, existsSync, readFileSync, mkdirSync } from 'fs';
import { join } from 'path';
import { saveFeatures } from '../FeatureTracker.js';

export interface ProbeResult {
  pkg: any | null;
  hasTsconfig: boolean;
  testCmd: string | null;
  buildCmd: string | null;
  lintCmd: string | null;
}

export function probeWorkspace(ws: string): ProbeResult {
  let pkg: any = null;
  try {
    const raw = readFileSync(join(ws, 'package.json'), 'utf-8');
    pkg = JSON.parse(raw);
  } catch {}
  const hasTsconfig = existsSync(join(ws, 'tsconfig.json'));
  const scripts = pkg?.scripts ?? {};
  const pick = (names: string[]): string | null => {
    for (const n of names) if (typeof scripts[n] === 'string' && scripts[n].trim()) return `${n} → ${scripts[n]}`;
    return null;
  };
  return {
    pkg,
    hasTsconfig,
    testCmd: pick(['test', 'test:unit']),
    buildCmd: pick(['build']),
    lintCmd: pick(['lint', 'typecheck', 'tsc']),
  };
}

export function buildAgentsMd(ws: string, probe: ProbeResult): string {
  const lines: string[] = [];
  lines.push('# Project Instructions (generated by /init)');
  lines.push('');
  lines.push('> 目录页（Codex AGENTS.md 语义）：路由 + 不变量 + 验证命令。');
  lines.push('> 完整项目文档：`docs/ZIS.md`（Zorge 目录页）→ `docs/ZIS-DETAILS/*`（按需阅读）。');
  lines.push('');
  lines.push(`Workspace: ${ws}`);
  const desc = probe.pkg?.description;
  if (desc) lines.push(`Overview: ${desc}`);
  lines.push('');
  if (probe.pkg?.dependencies || probe.pkg?.devDependencies) {
    lines.push('## Tech stack');
    const deps = { ...(probe.pkg?.dependencies ?? {}), ...(probe.pkg?.devDependencies ?? {}) };
    const names = Object.keys(deps).slice(0, 20).map((n) => `${n}@${deps[n]}`).join(', ');
    if (names) lines.push(names);
    lines.push('');
  }
  lines.push('## First-run commands');
  if (probe.buildCmd) lines.push(`- build: \`${probe.buildCmd}\``);
  if (probe.testCmd) lines.push(`- test:  \`${probe.testCmd}\``);
  if (probe.lintCmd) lines.push(`- lint:  \`${probe.lintCmd}\``);
  if (!probe.buildCmd && !probe.testCmd) lines.push('- (no package.json scripts detected — probe manually)');
  lines.push('');
  lines.push('## Verification commands');
  lines.push('Run these before claiming success (harness Feedback discipline):');
  if (probe.testCmd) lines.push(`- [ ] \`${probe.testCmd}\` passes`);
  if (probe.buildCmd) lines.push(`- [ ] \`${probe.buildCmd}\` passes`);
  if (probe.lintCmd) lines.push(`- [ ] \`${probe.lintCmd}\` passes`);
  if (probe.hasTsconfig) lines.push('- [ ] `tsc --noEmit` clean');
  lines.push('');
  lines.push('## Invariants');
  lines.push('- 测试必须通过（不允许“逻辑上应该通过”）');
  lines.push('- 验证命令的输出必须真实可见（EXIT_CODE:0 / PASS）');
  lines.push('');
  return lines.join('\n');
}

const command: Command = {
  name: 'init',
  description: '生成项目指令目录页（.zorge/AGENTS.md）+ feature_list.json 模板',
  category: 'config',
  usage: '/init',
  async execute(ctx: CommandContext, args: string[]): Promise<CommandResult> {
    const ws = ctx.session.workspace || process.cwd();
    const agentsPath = join(ws, '.zorge', 'AGENTS.md');
    const agentsExisting = existsSync(agentsPath);

    const probe = probeWorkspace(ws);
    const agents = buildAgentsMd(ws, probe);

    if (agentsExisting) {
      // idempotent: ask before overwrite; headless default = keep
      const answer = args[0] === '--force' || args[0] === '-f'
        ? 'y'
        : (await ctx.input.read(`${agentsPath} 已存在，覆盖? (y/n) > `).catch(() => 'n')).trim().toLowerCase();
      if (answer !== 'y') {
        ctx.renderer.info('已保留现有 AGENTS.md（未覆盖）');
        return {};
      }
    }

    try {
      mkdirSync(join(ws, '.zorge'), { recursive: true });
      writeFileSync(agentsPath, agents, 'utf-8');
      // feature_list.json template (only if missing — never clobber user data)
      const { featureListPath, loadFeatures } = await import('../FeatureTracker.js');
      if (!existsSync(featureListPath(ws))) saveFeatures(ws, []);
      // A-T12 (L02): environment self-description → .zorge/ENV.md
      try {
        const { describeEnvironment, renderEnvSelfDescription } = await import('../EnvContext.js');
        const envMd = renderEnvSelfDescription(describeEnvironment(ws));
        writeFileSync(join(ws, '.zorge', 'ENV.md'), envMd, 'utf-8');
        ctx.renderer.info('已生成 .zorge/ENV.md（环境自描述）');
      } catch {}
      ctx.renderer.success(`已生成 ${agentsPath}`);
      ctx.renderer.writeLine('验证命令探测:');
      if (probe.buildCmd) ctx.renderer.writeLine(`  build: ${probe.buildCmd}`);
      if (probe.testCmd) ctx.renderer.writeLine(`  test:  ${probe.testCmd}`);
      if (probe.lintCmd) ctx.renderer.writeLine(`  lint:  ${probe.lintCmd}`);
      ctx.renderer.writeLine(`  tsconfig: ${probe.hasTsconfig ? '有（tsc --noEmit 可验证）' : '无'}`);
      ctx.renderer.info('已创建空 feature_list.json（/feature add <标题> 开始追踪）');
    } catch (e: any) {
      ctx.renderer.error('初始化失败: ' + (e?.message || e));
    }
    return {};
  },
};

export default command;
